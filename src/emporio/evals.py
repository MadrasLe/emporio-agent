"""Scenario evals against the real model (scenarios in evals/scenarios.yaml).

    python -m emporio.evals                                   # every scenario, configured model
    python -m emporio.evals --model nvidia/... --no-fallback  # compare one model in isolation
    python -m emporio.evals --only pedido-atrasado,endereco
    python -m emporio.evals --write-conversations             # refresh conversations/*.md

Each run is saved to evals/results/<model>.json and evals/REPORT.md is rebuilt
from every saved run.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
import time
import unicodedata
import uuid
from dataclasses import replace
from datetime import datetime
from pathlib import Path

import yaml

from .agent import Assistant, load_runtime
from .config import PROJECT_ROOT, load_settings

EVALS_DIR = PROJECT_ROOT / "evals"
RESULTS_DIR = EVALS_DIR / "results"
CONVERSATIONS_DIR = PROJECT_ROOT / "conversations"


def _plain(text: str) -> str:
    return unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower()


def _contains(answer: str, spec: str) -> bool:
    return any(_plain(option) in _plain(answer) for option in spec.split("|"))


def _executed_tools(audit: list[dict]) -> list[str]:
    return [e["tool"] for e in audit if e.get("type") == "tool" and e["gate"]["outcome"] != "reject"]


def check_turn(turn: dict, answer: str, audit: list[dict]) -> list[dict]:
    executed = _executed_tools(audit)
    checks = []
    for spec in turn.get("expect_tools", []):
        checks.append({"check": f"calls {spec}", "ok": any(t in executed for t in spec.split("|"))})
    for name in turn.get("forbid_tools", []):
        checks.append({"check": f"does not run {name}", "ok": name not in executed})
    for spec in turn.get("must_include", []):
        checks.append({"check": f"says '{spec}'", "ok": _contains(answer, spec)})
    for spec in turn.get("must_not_include", []):
        checks.append({"check": f"never says '{spec}'", "ok": not _contains(answer, spec)})
    checks.append({"check": "no safe fallback", "ok": not any(e.get("fallback") for e in audit)})
    return checks


def run_scenario(assistant: Assistant, scenario: dict, pause: float) -> dict:
    thread_id = f"eval-{scenario['id']}-{uuid.uuid4().hex[:6]}"
    turns = []
    for turn in scenario["turns"]:
        start = time.time()
        try:
            result = assistant.reply(thread_id, turn["user"])
            answer, audit, error = result.answer, result.audit, None
            checks = check_turn(turn, answer, audit)
        except Exception as exc:  # rate limits etc. count as a failed turn, the run goes on
            answer, audit, error = "", [], f"{type(exc).__name__}: {exc}"
            checks = [{"check": "model call succeeds", "ok": False}]
        turns.append({"user": turn["user"], "answer": answer, "audit": audit, "checks": checks,
                      "latency_s": round(time.time() - start, 1), "error": error})
        if pause:
            time.sleep(pause)
    return {"id": scenario["id"], "title": scenario["title"], "example": scenario.get("example"),
            "why": scenario.get("why", ""), "passed": all(c["ok"] for t in turns for c in t["checks"]),
            "turns": turns}


def summarize(scenarios: list[dict]) -> dict:
    turns = [t for s in scenarios for t in s["turns"]]
    checks = [c for t in turns for c in t["checks"]]
    events = [e for t in turns for e in t["audit"]]
    return {
        "scenarios_passed": sum(s["passed"] for s in scenarios),
        "scenarios": len(scenarios),
        "checks_passed": sum(c["ok"] for c in checks),
        "checks": len(checks),
        "avg_latency_s": round(sum(t["latency_s"] for t in turns) / max(len(turns), 1), 1),
        "revisions": sum(1 for e in events if e.get("type") == "constitution" and e.get("ok") is False),
        "safe_fallbacks": sum(1 for e in events if e.get("fallback")),
        "gate_blocks": sum(1 for e in events if e.get("type") == "tool" and e["gate"]["outcome"] == "reject"),
        "served_by_fallback_model": sum(1 for e in events if e.get("type") == "llm_fallback"),
        "errors": sum(1 for t in turns if t["error"]),
    }


# --- reporting ---------------------------------------------------------------------------

def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def write_report() -> Path:
    runs = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(RESULTS_DIR.glob("*.json"))]
    lines = [
        "# Eval report",
        "",
        "Generated by `python -m emporio.evals` from every run in `evals/results/`. Scenarios live in "
        "`evals/scenarios.yaml`; the clock is pinned (`EMPORIO_NOW`) so deadlines are reproducible.",
        "",
        "| Run | Scenarios | Checks | Avg latency/turn | Revisions | Safe fallbacks | Gate blocks | Errors |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for run in runs:
        s = run["summary"]
        lines.append(f"| `{run['label']}` | {s['scenarios_passed']}/{s['scenarios']} | "
                     f"{s['checks_passed']}/{s['checks']} | {s['avg_latency_s']}s | {s['revisions']} | "
                     f"{s['safe_fallbacks']} | {s['gate_blocks']} | {s['errors']} |")
    lines += ["", "*Revisions*: answers the constitution sent back once. *Gate blocks*: tool calls the "
              "constitution refused (expected in the identity scenarios).", "", "## By scenario", ""]
    ids = list(dict.fromkeys(s["id"] for run in runs for s in run["scenarios"]))
    lines.append("| Scenario | " + " | ".join(f"`{run['label']}`" for run in runs) + " |")
    lines.append("|---|" + "---|" * len(runs))
    for scenario_id in ids:
        cells = []
        for run in runs:
            found = next((s for s in run["scenarios"] if s["id"] == scenario_id), None)
            cells.append("—" if found is None else "✅" if found["passed"] else "❌")
        lines.append(f"| {scenario_id} | " + " | ".join(cells) + " |")
    failures = [(run, s) for run in runs for s in run["scenarios"] if not s["passed"]]
    if failures:
        lines += ["", "## Failed checks", ""]
        for run, scenario in failures:
            failed = [f"turn {i + 1}: {c['check']}" for i, t in enumerate(scenario["turns"])
                      for c in t["checks"] if not c["ok"]]
            lines.append(f"- `{run['label']}` · **{scenario['id']}** — " + "; ".join(failed))
    report = EVALS_DIR / "REPORT.md"
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return report


def _describe_event(event: dict) -> str | None:
    kind = event.get("type")
    if kind == "tool":
        args = ", ".join(f"{k}={json.dumps(v, ensure_ascii=False)}" for k, v in event["args"].items()
                         if v not in (None, "", []))
        gate = event["gate"]
        if gate["outcome"] == "reject":
            return f"⛔ `{event['tool']}({args})` bloqueado pela constituição: {gate['reason']} (`{gate['rule_id']}`)"
        line = f"🔧 `{event['tool']}({args})`"
        if decision := event.get("decision"):
            line += f" → regra `{decision['rule_id']}`"
        return line
    if kind == "constitution":
        if event.get("fallback"):
            return "🛡️ constituição: revisão falhou de novo, resposta trocada por encaminhamento"
        if not event.get("ok"):
            return "🛡️ constituição barrou o rascunho (" + "; ".join(
                f"{v['principle']}: {v['message']}" for v in event["violations"]) + ") e pediu revisão"
        return "🛡️ constituição: aprovada" + (" após revisão" if event.get("revised") else "")
    if kind == "llm_fallback":
        return f"↪ respondido pelo modelo reserva `{event['model']}`"
    return None


def write_conversation(scenario: dict, label: str, now: datetime) -> Path:
    lines = [
        f"# {scenario['title']}",
        "",
        f"> {scenario['why']}",
        ">",
        f"> Modelo: `{label}` · relógio simulado: {now:%d/%m/%Y %H:%M} · gerado com "
        "`python -m emporio.evals --write-conversations` (conversa real com o modelo, não editada).",
        "",
    ]
    for turn in scenario["turns"]:
        lines += [f"**Cliente:** {turn['user']}", "", f"**Lia:** {turn['answer']}", ""]
        details = [d for d in (_describe_event(e) for e in turn["audit"]) if d]
        if details:
            lines += ["<details><summary>Bastidores</summary>", ""] + [f"- {d}" for d in details] + \
                     ["", "</details>", ""]
    CONVERSATIONS_DIR.mkdir(exist_ok=True)
    path = CONVERSATIONS_DIR / f"{scenario['example']:02d}-{scenario['id']}.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def _first_relevant_rank(products: list, relevant: set[int]) -> int | None:
    return next((rank for rank, p in enumerate(products, start=1) if p.id in relevant), None)


def run_retrieval(settings) -> Path:
    """Search-only benchmark: BM25 vs hybrid on customer-style paraphrases (hit@1, hit@3, MRR)."""

    from .agent.runtime import build_semantic_index
    from .data.loader import load_store_data
    from .domain.catalog import search

    data = load_store_data(settings.data_dir)
    semantic = build_semantic_index(settings, data)
    if semantic is None:
        raise SystemExit("retrieval benchmark needs EMBEDDING_MODEL and LLM_API_KEY")
    cases = yaml.safe_load((EVALS_DIR / "retrieval.yaml").read_text(encoding="utf-8"))

    rows, ranks = [], {"bm25": [], "hybrid": []}
    for case in cases:
        relevant = set(case["relevant"])
        bm25 = _first_relevant_rank(search(data, query=case["query"]).products, relevant)
        hybrid = _first_relevant_rank(search(data, query=case["query"], semantic=semantic).products, relevant)
        ranks["bm25"].append(bm25)
        ranks["hybrid"].append(hybrid)
        names = ", ".join(data.products[i].name for i in case["relevant"][:2])
        rows.append(f"| {case['query']} | {names} | {bm25 or '—'} | {hybrid or '—'} |")
        print(f"  bm25={bm25 or '-':>2}  hybrid={hybrid or '-':>2}  {case['query']}")

    def metrics(values: list[int | None]) -> str:
        n = len(values)
        hit1 = sum(1 for r in values if r == 1) / n
        hit3 = sum(1 for r in values if r and r <= 3) / n
        mrr = sum(1 / r for r in values if r) / n
        return f"{hit1:.0%} | {hit3:.0%} | {mrr:.2f}"

    lines = [
        "# Retrieval benchmark",
        "",
        f"Generated by `python -m emporio.evals --retrieval` (embedding model `{settings.embedding_model}`). "
        "Each query is a customer-style paraphrase from `evals/retrieval.yaml`; the number is the position "
        "of the first relevant product in what `search_products` returns (— = not returned).",
        "",
        "| Mode | hit@1 | hit@3 | MRR |",
        "|---|---|---|---|",
        f"| BM25 only | {metrics(ranks['bm25'])} |",
        f"| Hybrid (BM25 + embeddings, RRF) | {metrics(ranks['hybrid'])} |",
        "",
        "| Query | Relevant (e.g.) | BM25 rank | Hybrid rank |",
        "|---|---|---|---|",
        *rows,
    ]
    report = EVALS_DIR / "RETRIEVAL.md"
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return report


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description="Run scenario evals against the configured model.")
    parser.add_argument("--model", help="override LLM_MODEL")
    parser.add_argument("--no-fallback", action="store_true", help="disable OpenRouter fallback models")
    parser.add_argument("--no-embeddings", action="store_true", help="BM25-only product search")
    parser.add_argument("--only", help="comma-separated scenario ids")
    parser.add_argument("--pause", type=float, default=0.5, help="seconds between turns (rate limits)")
    parser.add_argument("--write-conversations", action="store_true", help="refresh conversations/*.md")
    parser.add_argument("--verbose", action="store_true", help="print the transcript of failed turns")
    parser.add_argument("--retrieval", action="store_true", help="only run the search benchmark (BM25 vs hybrid)")
    args = parser.parse_args(argv)

    if args.retrieval:
        print(f"Report: {run_retrieval(load_settings())}")
        return 0

    settings = load_settings()
    if args.model:
        settings = replace(settings, llm_model=args.model)
    if args.no_fallback:
        settings = replace(settings, llm_fallback_models=())
    if args.no_embeddings:
        settings = replace(settings, embedding_model="")
    settings = replace(settings, state_dir=Path(tempfile.mkdtemp(prefix="emporio-eval-")))  # tickets go here
    assistant = Assistant(load_runtime(settings))

    scenarios = yaml.safe_load((EVALS_DIR / "scenarios.yaml").read_text(encoding="utf-8"))
    if args.only:
        wanted = set(args.only.split(","))
        scenarios = [s for s in scenarios if s["id"] in wanted]

    label = (settings.llm_model + ("" if settings.llm_fallback_models else " (no fallback)")
             + ("" if settings.embedding_model else " · BM25 only"))
    print(f"Running {len(scenarios)} scenarios on {label} (now = {settings.now():%Y-%m-%d %H:%M})")
    results = []
    for scenario in scenarios:
        outcome = run_scenario(assistant, scenario, args.pause)
        results.append(outcome)
        failed = [c["check"] for t in outcome["turns"] for c in t["checks"] if not c["ok"]]
        print(f"  {'PASS' if outcome['passed'] else 'FAIL'}  {scenario['id']}" + (f"  -> {failed}" if failed else ""))
        if args.verbose and failed:
            for turn in outcome["turns"]:
                if not all(c["ok"] for c in turn["checks"]):
                    print(f"      customer: {turn['user']}\n      tools: {_executed_tools(turn['audit'])}"
                          f"\n      lia: {turn['answer'] or turn['error']}\n")

    summary = summarize(results)
    if not args.only:  # partial runs are for debugging; only full runs go into the report
        RESULTS_DIR.mkdir(parents=True, exist_ok=True)
        run = {"label": label, "model": settings.llm_model, "fallback_models": list(settings.llm_fallback_models),
               "run_at": datetime.now().isoformat(timespec="seconds"), "now": settings.now().isoformat(),
               "summary": summary, "scenarios": results}
        (RESULTS_DIR / f"{_slug(label)}.json").write_text(
            json.dumps(run, ensure_ascii=False, indent=2, default=str), encoding="utf-8")
        print(f"Report: {write_report()}")

    if args.write_conversations:
        for scenario in results:
            if not scenario.get("example"):
                continue
            if scenario["passed"]:
                print(f"  wrote {write_conversation(scenario, label, settings.now())}")
            else:
                print(f"  skipped {scenario['id']}: it failed, conversation not refreshed")

    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
